// Жидкие экстракты: формулировки производителя, разложенные по блокам. Убраны только остатки поста
// для соцсетей («Сохраните её…») и обрывки вроде «situational (запрос)» — содержание не менять
function Intro({ title, children }: { title: string; children: ReactNode }) {
  return (
    <div className="rounded-lg bg-linear-to-br from-brass/15 via-mist to-mist p-4 ring-1 ring-brass/25">
      <p className="font-display text-base text-ink">{title}</p>
      <div className="mt-2 flex flex-col gap-2">{children}</div>
    </div>
  )
}

function Callout({ tone, children }: { tone: 'warning' | 'tip'; children: ReactNode }) {
  return (
    <div className={`mt-3 rounded-lg p-3.5 ring-1 ${tone === 'warning' ? 'bg-red-500/10 ring-red-400/30' : 'bg-brass/10 ring-brass/30'}`}>
      {children}
    </div>
  )
}

function Schedule({ rows }: { rows: { when: string; text: ReactNode }[] }) {
  return (
    <div className="flex flex-col gap-2">
      {rows.map((row) => (
        <div key={row.when} className="flex items-start gap-3">
          <span className="mt-0.5 w-24 shrink-0 rounded-full bg-brass/15 px-2 py-1 text-center text-[11px] font-semibold uppercase tracking-wide text-brass">
            {row.when}
          </span>
          <span>{row.text}</span>
        </div>
      ))}
    </div>
  )
}

function Steps({ items }: { items: { lead: string; text: string }[] }) {
  return (
    <ol className="flex flex-col gap-2.5">
      {items.map((step, i) => (
        <li key={step.lead} className="flex items-start gap-3">
          <span className="flex h-5 w-5 shrink-0 items-center justify-center rounded-full bg-brass/15 text-[11px] font-semibold text-brass">{i + 1}</span>
          <span><span className="font-semibold text-ink">{step.lead}</span> {step.text}</span>
        </li>
      ))}
    </ol>
  )
}

